"""Observability (Blueprint §9): trace IDs, latency headers, structured logs,
in-process fallback counters, a bounded per-IP token-bucket rate limiter, and
baseline security headers.

Honest limitation: counters and rate limiting are per-process. In multi-instance
production these move to Redis; the interface stays identical.
"""
import json
import logging
import time
import uuid
from contextvars import ContextVar
from threading import Lock

from fastapi import Request
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.responses import JSONResponse, Response

from .config import settings

# Correlates every log line emitted while handling a request.
trace_id_var: ContextVar[str] = ContextVar("trace_id", default="-")


class _JsonFormatter(logging.Formatter):
    def format(self, record: logging.LogRecord) -> str:
        payload = {
            "ts": self.formatTime(record, "%Y-%m-%dT%H:%M:%S%z"),
            "level": record.levelname,
            "logger": record.name,
            "trace_id": getattr(record, "trace_id", trace_id_var.get()),
            "msg": record.getMessage(),
        }
        for key in ("method", "path", "status", "latency_ms"):
            if hasattr(record, key):
                payload[key] = getattr(record, key)
        if record.exc_info:
            payload["exc"] = self.formatException(record.exc_info)
        return json.dumps(payload, default=str)


def _configure_logging() -> logging.Logger:
    log = logging.getLogger("cdis")
    log.setLevel(logging.INFO)
    log.propagate = False
    handler = logging.StreamHandler()
    if settings.log_json:
        handler.setFormatter(_JsonFormatter())
    else:
        handler.setFormatter(logging.Formatter(
            "%(asctime)s %(levelname)s [%(trace_id)s] %(message)s"))
    log.handlers = [handler]
    return log


logger = _configure_logging()
if settings.jwt_secret_autogenerated:
    logger.warning("JWT_SECRET not set — using a random per-process secret (dev only). "
                   "Tokens will not survive restarts or work across replicas.",
                   extra={"trace_id": "-"})


class Counters:
    def __init__(self) -> None:
        self._lock = Lock()
        self._data: dict[str, int] = {}

    def bump(self, key: str) -> None:
        with self._lock:
            self._data[key] = self._data.get(key, 0) + 1

    def snapshot(self) -> dict[str, int]:
        with self._lock:
            return dict(self._data)


counters = Counters()


class _Bucket:
    __slots__ = ("tokens", "updated")

    def __init__(self, tokens: float) -> None:
        self.tokens = tokens
        self.updated = time.monotonic()


# CSP allows the SPA's inline styles/handlers (no build step) but blocks external
# scripts, framing, and cross-origin exfiltration — a real reduction in XSS blast
# radius. Fonts are the only third-party origins the pages use.
_CSP = (
    "default-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'; "
    "object-src 'none'; img-src 'self' data:; connect-src 'self'; "
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; "
    "font-src https://fonts.gstatic.com; script-src 'self' 'unsafe-inline'"
)

# Keep the security-header set small, correct, and non-breaking for the SPA.
_SECURITY_HEADERS = {
    "X-Content-Type-Options": "nosniff",
    "X-Frame-Options": "DENY",
    "Referrer-Policy": "no-referrer",
    "Cross-Origin-Opener-Policy": "same-origin",
    "Content-Security-Policy": _CSP,
}


class ObservabilityMiddleware(BaseHTTPMiddleware):
    # Evict buckets untouched for this long to bound memory under IP churn.
    _BUCKET_TTL_S = 300.0
    _SWEEP_EVERY = 1000

    def __init__(self, app):
        super().__init__(app)
        self._buckets: dict[str, _Bucket] = {}
        self._lock = Lock()
        self._requests_since_sweep = 0

    def _client_ip(self, request: Request) -> str:
        if settings.trust_proxy_headers:
            fwd = request.headers.get("x-forwarded-for", "")
            if fwd:
                return fwd.split(",")[0].strip()
        return request.client.host if request.client else "unknown"

    def _sweep_locked(self, now: float) -> None:
        stale = [ip for ip, b in self._buckets.items()
                 if now - b.updated > self._BUCKET_TTL_S]
        for ip in stale:
            del self._buckets[ip]

    def _allow(self, key: str, rate: int) -> bool:
        with self._lock:
            self._requests_since_sweep += 1
            now = time.monotonic()
            if self._requests_since_sweep >= self._SWEEP_EVERY:
                self._sweep_locked(now)
                self._requests_since_sweep = 0
            b = self._buckets.get(key)
            if b is None:
                b = self._buckets[key] = _Bucket(float(rate))
            b.tokens = min(float(rate), b.tokens + (now - b.updated) * rate / 60.0)
            b.updated = now
            if b.tokens < 1.0:
                return False
            b.tokens -= 1.0
            return True

    async def dispatch(self, request: Request, call_next):
        trace_id = uuid.uuid4().hex[:16]
        token = trace_id_var.set(trace_id)
        is_api = request.url.path.startswith("/api")
        try:
            if is_api:
                ip = self._client_ip(request)
                is_auth = request.url.path.startswith("/api/auth")
                limit = (settings.auth_rate_limit_per_minute if is_auth
                         else settings.rate_limit_per_minute)
                if not self._allow(f"{'auth' if is_auth else 'api'}:{ip}", limit):
                    counters.bump("rate_limited")
                    resp = JSONResponse(
                        {"detail": "Too many requests. Wait a moment and try again.",
                         "trace_id": trace_id},
                        status_code=429,
                    )
                    resp.headers["Retry-After"] = "1"
                    self._finalize(resp, trace_id, None)
                    return resp

            start = time.perf_counter()
            response: Response = await call_next(request)
            elapsed_ms = (time.perf_counter() - start) * 1000
            self._finalize(response, trace_id, elapsed_ms)
            if is_api:
                logger.info("request", extra={
                    "trace_id": trace_id, "method": request.method,
                    "path": request.url.path, "status": response.status_code,
                    "latency_ms": round(elapsed_ms, 1)})
            return response
        finally:
            trace_id_var.reset(token)

    @staticmethod
    def _finalize(response: Response, trace_id: str, elapsed_ms: float | None) -> None:
        response.headers["X-Trace-Id"] = trace_id
        if elapsed_ms is not None:
            response.headers["X-Response-Time-Ms"] = f"{elapsed_ms:.1f}"
        for key, value in _SECURITY_HEADERS.items():
            response.headers.setdefault(key, value)
        if settings.is_production:  # HSTS only where TLS is terminated
            response.headers.setdefault("Strict-Transport-Security",
                                        "max-age=63072000; includeSubDomains")
