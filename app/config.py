"""Environment-driven configuration. No framework magic — explicit and testable."""
import os
import secrets


class ConfigError(RuntimeError):
    """Raised at boot when a production-required setting is missing."""


def _bool(name: str, default: str = "0") -> bool:
    return os.getenv(name, default).strip().lower() in ("1", "true", "yes", "on")


class Settings:
    def __init__(self) -> None:
        self.app_name = "CDIS — Career Decision Intelligence System"
        self.version = "2.0.0"
        self.app_env = os.getenv("APP_ENV", "dev").strip().lower()
        self.is_production = self.app_env == "production"

        self.database_url = os.getenv("DATABASE_URL", "sqlite:///./cdis.db")

        # JWT secret: in production it MUST be provided. In dev we generate one so
        # the zero-config quickstart still works (with a logged warning elsewhere).
        secret = os.getenv("JWT_SECRET", "").strip()
        if not secret:
            if self.is_production:
                raise ConfigError(
                    "JWT_SECRET is required when APP_ENV=production. "
                    "A per-process random secret would reject tokens across restarts/replicas."
                )
            secret = secrets.token_hex(32)
            self.jwt_secret_autogenerated = True
        else:
            self.jwt_secret_autogenerated = False
        self.jwt_secret = secret
        self.jwt_ttl_hours = int(os.getenv("JWT_TTL_HOURS", "24"))

        self.anthropic_api_key = os.getenv("ANTHROPIC_API_KEY", "").strip()
        self.github_token = os.getenv("GITHUB_TOKEN", "").strip()
        self.llm_model = os.getenv("LLM_MODEL", "claude-sonnet-4-6")
        self.llm_timeout_s = float(os.getenv("LLM_TIMEOUT_S", "4.0"))
        self.llm_connect_timeout_s = float(os.getenv("LLM_CONNECT_TIMEOUT_S", "1.5"))
        self.llm_max_retries = int(os.getenv("LLM_MAX_RETRIES", "2"))
        # Runtime-togglable for the graceful-degradation demo (kill switch).
        self.simulate_llm_down = _bool("SIMULATE_LLM_DOWN")

        self.rate_limit_per_minute = int(os.getenv("RATE_LIMIT_PER_MINUTE", "240"))
        # Auth endpoints are brute-force targets — throttled far tighter than the
        # general API budget.
        self.auth_rate_limit_per_minute = int(os.getenv("AUTH_RATE_LIMIT_PER_MINUTE", "10"))
        # When true, honor the first X-Forwarded-For hop for the client IP.
        # Only enable behind a trusted proxy/load balancer.
        self.trust_proxy_headers = _bool("TRUST_PROXY_HEADERS")

        # Interactive API docs expose the full schema — off in production by default.
        self.enable_docs = _bool("ENABLE_DOCS", "0" if self.is_production else "1")

        # Hard cap on uploaded resume files (bytes). Text ingest is capped in schemas.
        self.max_upload_bytes = int(os.getenv("MAX_UPLOAD_BYTES", str(2 * 1024 * 1024)))

        self.log_json = _bool("LOG_JSON", "1" if self.is_production else "0")

        # CORS allowed origins. Comma-separated in the env var.
        # Dev default: ["*"] (permissive). Production default: [] (block all cross-origin
        # unless explicitly configured).
        cors_raw = os.getenv("CORS_ORIGINS", "" if self.is_production else "*").strip()
        self.cors_origins: list[str] = (
            [o.strip() for o in cors_raw.split(",") if o.strip()] if cors_raw else []
        )


settings = Settings()
